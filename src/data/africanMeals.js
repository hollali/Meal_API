function toMeal(item) {
  const meal = {
    idMeal: `af-${item.id}`,
    strMeal: item.name,
    strMealThumb: item.thumb,
    strCategory: item.category,
    strArea: item.country,
    strCountry: item.country,
    strRegion: item.region,
    strInstructions: item.steps.join('\n'),
    strTags: item.tags,
    strSource: `${WIKI}${item.wiki}`,
    strImageSource: item.thumb ? `${WIKI}${item.wiki}` : '',
    strYoutube: '',
  };
  item.ingredients.forEach(([name, measure], index) => {
    meal[`strIngredient${index + 1}`] = name;
    meal[`strMeasure${index + 1}`] = measure;
  });
  return meal;
}

